#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_define_is_a_name_a_value_and_maybe_a_comment() {
        assert_eq!(
            define("#define\tPCI_VENDOR_HAUPPAUGE\t0x0070\t\t/* Hauppauge */"),
            Some(Define {
                name: "PCI_VENDOR_HAUPPAUGE",
                value: "0x0070",
                comment: Some("Hauppauge"),
            })
        );
        assert_eq!(
            define("#define\tMII_MODEL_ENABLESEMI_LU3X31FT\t0x0001"),
            Some(Define {
                name: "MII_MODEL_ENABLESEMI_LU3X31FT",
                value: "0x0001",
                comment: None,
            })
        );
        assert_eq!(
            define("#define\tMII_STR_xxDEC_xxDC\t\"DC 21143\""),
            Some(Define {
                name: "MII_STR_xxDEC_xxDC",
                value: "\"DC 21143\"",
                comment: None,
            })
        );
        for not in [
            "",
            "/* 3Com products */",
            "#define GUARD",
            "#include <x.h>",
            " * text",
        ] {
            assert_eq!(define(not), None, "{not}");
        }
    }

    #[test]
    fn the_constants_keep_the_headers_order_groups_and_comments() {
        let header = "/* vendors */\n\
                      #define\tUSB_VENDOR_HP\t0x03F0\t\t/* Hewlett Packard */\n\
                      #define\tUSB_VENDOR_NEC\t0x0409\t\t/* NEC. */\n\
                      \n\
                      /* HP products */\n\
                      #define\tUSB_PRODUCT_HP_895C\t0x0004\n";
        assert_eq!(
            constants(&TABLES[1], header).unwrap(),
            "/// `USB_VENDOR_HP`: Hewlett Packard.\n\
             pub const USB_VENDOR_HP: u16 = 0x03f0;\n\
             /// `USB_VENDOR_NEC`: NEC.\n\
             pub const USB_VENDOR_NEC: u16 = 0x0409;\n\
             \n\
             /// `USB_PRODUCT_HP_895C`.\n\
             pub const USB_PRODUCT_HP_895C: u16 = 0x0004;\n"
        );
        let mii = "#define\tMII_OUI_AMD\t0x00001a\t/* AMD */\n#define\tMII_STR_AMD_79C873\t\"Am79C873\"\n";
        assert_eq!(
            constants(&TABLES[2], mii).unwrap(),
            "/// `MII_OUI_AMD`: AMD.\npub const MII_OUI_AMD: u32 = 0x00001a;\n\
             /// `MII_STR_AMD_79C873`.\npub const MII_STR_AMD_79C873: &str = \"Am79C873\";\n"
        );
    }

    #[test]
    fn what_the_table_does_not_know_is_an_error() {
        assert!(constants(&TABLES[0], "#define\tUSB_VENDOR_HP\t0x03f0\n").is_err());
        assert!(constants(&TABLES[0], "#define\tPCI_VENDOR_X\t12\n").is_err());
        assert!(constants(&TABLES[2], "#define\tMII_STR_X\t\"a\\\\b\"\n").is_err());
        assert!(constants(&TABLES[0], "/* nothing */\n").is_err());
    }

    #[test]
    fn only_the_part_between_the_marker_and_the_zones_end_is_replaced() {
        let old = format!("/* <CODE> */\n//! docs\n\n{MARKER}\n\nold\n{CODE_END}\n\ntail\n");
        assert_eq!(
            rewrite(&TABLES[0], &old, "new\n").unwrap(),
            format!("/* <CODE> */\n//! docs\n\n{MARKER}\n\nnew\n{CODE_END}\n\ntail\n")
        );
        assert!(rewrite(&TABLES[0], "no marker\n", "new\n").is_err());
        assert!(rewrite(&TABLES[0], &format!("{MARKER}\nno end\n"), "new\n").is_err());
    }
}
