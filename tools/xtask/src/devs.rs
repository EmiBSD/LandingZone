//! `cargo xtask gen-devs [--check]`: the device id tables OpenBSD generates.
//!
//! `sys/dev/pci/pcidevs.h`, `sys/dev/usb/usbdevs.h` and `sys/dev/mii/miidevs.h` are written by
//! `devlist2h.awk` from the lists beside them (`pcidevs`, `usbdevs`, `miidevs`) and checked
//! in. Their ports are the same tables: every `#define` of the header as a `pub const`, in
//! the header's order, with the header's comment as its doc.
//!
//! This command writes that part of each port from the header at the pin: everything
//! between the line [`MARKER`] and the end of the file's code zone. What stands before the
//! marker (the licence zone, the `//!` docs, an inner attribute) is the file's own and is
//! kept, and so is what follows the code zone. `--check` (`just check-devs`, in `ci`) writes
//! nothing and fails when a file differs from what the command would write, so a pin that
//! moves a header, or a hand edit below the marker, is caught.
//!
//! The headers are converted, not regenerated from the lists: what OpenBSD commits is the
//! header, and `ports.toml` tracks its blob.

use std::fs;
use std::path::Path;

use crate::Result;

/// The line that starts the generated part of a table's Rust file.
const MARKER: &str =
    "// Generated by `cargo xtask gen-devs` from the header at the pin; do not edit below.";

/// The line that ends a file's code zone.
const CODE_END: &str = "/* </CODE> */";

/// One generated table: the C header, its port, and the type of a define by its prefix.
struct Table {
    /// The header, relative to `reference/openbsd-src`.
    header: &'static str,
    /// The port, relative to the workspace root.
    rust: &'static str,
    /// `(prefix of the define's name, Rust type)`.
    kinds: &'static [(&'static str, &'static str)],
}

/// The tables `gen-devs` writes. The types are what the kernel reads the ids as:
/// `pci_vendor`/`pci_product` give `u32`, `idVendor`/`idProduct` are `u16` once read, and
/// `struct mii_phydesc` holds `u_int32_t` ids and a name.
const TABLES: [Table; 3] = [
    Table {
        header: "sys/dev/pci/pcidevs.h",
        rust: "sys/dev/pci/pcidevs.rs",
        kinds: &[("PCI_VENDOR_", "u32"), ("PCI_PRODUCT_", "u32")],
    },
    Table {
        header: "sys/dev/usb/usbdevs.h",
        rust: "sys/dev/usb/usbdevs.rs",
        kinds: &[("USB_VENDOR_", "u16"), ("USB_PRODUCT_", "u16")],
    },
    Table {
        header: "sys/dev/mii/miidevs.h",
        rust: "sys/dev/mii/miidevs.rs",
        kinds: &[
            ("MII_OUI_", "u32"),
            ("MII_MODEL_", "u32"),
            ("MII_STR_", "&str"),
        ],
    },
];

/// One `#define NAME VALUE /* comment */` line of a header.
#[derive(Debug, PartialEq, Eq)]
struct Define<'a> {
    name: &'a str,
    value: &'a str,
    comment: Option<&'a str>,
}

/// The define on `line`, if it is one with a value.
fn define(line: &str) -> Option<Define<'_>> {
    let rest = line.strip_prefix("#define")?;
    let rest = rest.strip_prefix([' ', '\t'])?.trim_start();
    let end = rest.find(char::is_whitespace)?;
    let (name, rest) = rest.split_at(end);
    let rest = rest.trim_start();
    let (value, rest) = match rest.strip_prefix('"') {
        Some(after) => {
            let close = after.find('"')?;
            rest.split_at(close + 2)
        }
        None => {
            let end = rest
                .find(|c: char| c.is_whitespace() || c == '/')
                .unwrap_or(rest.len());
            rest.split_at(end)
        }
    };
    if value.is_empty() {
        return None;
    }
    let comment = rest
        .find("/*")
        .and_then(|start| {
            let text = &rest[start + 2..];
            text.find("*/").map(|end| text[..end].trim())
        })
        .filter(|c| !c.is_empty());
    Some(Define {
        name,
        value,
        comment,
    })
}

/// `d` as Rust: its doc line and its `pub const`.
fn constant(table: &Table, d: &Define<'_>) -> Result<String> {
    let Some((_, ty)) = table.kinds.iter().find(|(p, _)| d.name.starts_with(p)) else {
        return Err(format!(
            "{}: `{}` is none of the table's kinds",
            table.header, d.name
        )
        .into());
    };
    let value = if *ty == "&str" {
        let plain = |c: char| c == ' ' || (c.is_ascii_graphic() && c != '\\' && c != '"');
        let inner = d
            .value
            .strip_prefix('"')
            .and_then(|v| v.strip_suffix('"'))
            .filter(|v| v.chars().all(plain));
        match inner {
            Some(_) => d.value.to_string(),
            None => {
                return Err(format!("{}: `{}` is not a plain string", table.header, d.name).into());
            }
        }
    } else {
        let digits = d
            .value
            .strip_prefix("0x")
            .filter(|h| !h.is_empty() && h.chars().all(|c| c.is_ascii_hexdigit()));
        match digits {
            Some(h) => format!("0x{}", h.to_ascii_lowercase()),
            None => {
                return Err(
                    format!("{}: `{}` is not a hexadecimal id", table.header, d.name).into(),
                );
            }
        }
    };
    let doc = match d.comment {
        Some(c) if c.ends_with('.') => format!("/// `{}`: {c}", d.name),
        Some(c) => format!("/// `{}`: {c}.", d.name),
        None => format!("/// `{}`.", d.name),
    };
    Ok(format!("{doc}\npub const {}: {ty} = {value};\n", d.name))
}

/// Every define of the header `text` as Rust, in order; one blank line where the header has
/// anything else between two defines (a comment, a blank line), as between its groups.
fn constants(table: &Table, text: &str) -> Result<String> {
    let mut out = String::new();
    let mut gap = false;
    for line in text.lines() {
        match define(line) {
            Some(d) => {
                if gap && !out.is_empty() {
                    out.push('\n');
                }
                gap = false;
                out.push_str(&constant(table, &d)?);
            }
            None => gap = true,
        }
    }
    if out.is_empty() {
        return Err(format!("{}: no define found", table.header).into());
    }
    Ok(out)
}

/// The port `old` with its generated part replaced by `consts`.
fn rewrite(table: &Table, old: &str, consts: &str) -> Result<String> {
    let Some(at) = old.find(MARKER) else {
        return Err(format!("{}: no `{MARKER}` line", table.rust).into());
    };
    let head = &old[..at + MARKER.len()];
    let Some(end) = old[at..].find(CODE_END) else {
        return Err(format!("{}: no `{CODE_END}` after the marker", table.rust).into());
    };
    let tail = &old[at + end..];
    Ok(format!("{head}\n\n{consts}{tail}"))
}

/// `cargo xtask gen-devs [--check]` (module docs).
pub fn gen_devs(root: &Path, check: bool) -> Result<()> {
    let src = root.join("reference/openbsd-src");
    let mut stale = Vec::new();
    for table in &TABLES {
        let header = src.join(table.header);
        let text = fs::read_to_string(&header).map_err(|e| format!("{}: {e}", header.display()))?;
        let path = root.join(table.rust);
        let old = fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
        let new = rewrite(table, &old, &constants(table, &text)?)?;
        if new == old {
            continue;
        }
        if check {
            stale.push(table.rust);
        } else {
            fs::write(&path, new).map_err(|e| format!("{}: {e}", path.display()))?;
            println!("gen-devs: wrote {}", table.rust);
        }
    }
    if !stale.is_empty() {
        return Err(format!(
            "gen-devs: {} differ(s) from the header at the pin; run `just gen-devs`",
            stale.join(", ")
        )
        .into());
    }
    if check {
        println!("gen-devs: {} files up to date", TABLES.len());
    }
    Ok(())
}
